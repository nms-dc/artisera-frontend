// Generates src/core/ui/icons.generated.ts: only the mdi icons the app uses, bundled so the UI never
// calls the public Iconify API at runtime (works offline / behind a firewall / under a strict CSP).
// Run `npm run icons` after adding a new "mdi:..." icon name anywhere in src/.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { getIcons } from '@iconify/utils';

const walk = (dir) =>
  readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : /\.(ts|tsx)$/.test(f) && !f.endsWith('icons.generated.ts') ? [p] : [];
  });

const names = new Set();
for (const file of walk('src')) for (const m of readFileSync(file, 'utf8').matchAll(/mdi:([a-z0-9-]+)/g)) names.add(m[1]);

const mdi = JSON.parse(readFileSync('node_modules/@iconify-json/mdi/icons.json', 'utf8'));
const subset = getIcons(mdi, [...names].sort());
const missing = [...names].filter((n) => !(subset?.icons?.[n] || subset?.aliases?.[n]));
if (!subset || missing.length) {
  console.error('Unknown mdi icons:', missing.join(', '));
  process.exit(1);
}
const out = `// GENERATED by scripts/build-icons.mjs — do not edit. Run \`npm run icons\`.\nimport { addCollection } from '@iconify/react';\n\naddCollection(${JSON.stringify(subset)});\n`;
writeFileSync('src/core/ui/icons.generated.ts', out);
console.log(`Bundled ${names.size} icons (${(out.length / 1024).toFixed(1)} KB)`);
